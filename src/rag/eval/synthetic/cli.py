"""Command line of the synthetic question sets (spec P1-05, design s14-2).

uv run python -m rag.eval.synthetic sample --kb hf_docs [--n 420] [--seed 0] [--span-chars 2000]
    [--min-chars 400] [--no-exclude-public] [--label L] [--out-dir D] [--extend RUN]
uv run python -m rag.eval.synthetic generate --run DIR [--limit N] [--concurrency 4] [--batch 20]
uv run python -m rag.eval.synthetic critique --run DIR [--concurrency 4] [--batch 60]
uv run python -m rag.eval.synthetic project --run DIR [--n 420]
uv run python -m rag.eval.synthetic build --run DIR --kb hf_docs [--seed 0] [--holdout-share 0.5]
    [--min-each 100] [--max-copy-run 6] [--out-dir D]

`sample` reads and cleans every page (no model, no ES) and writes the spans; `generate` (one
`deepseek-v4-flash` call per span) and `critique` (three `qwen/qwen3.6-flash` calls per question)
cost money, write every batch as it finishes and resume where they stopped (records with a
gateway error are tried again); `project` estimates the cost of n spans from the run's ledger
lines; `build` filters, splits and writes `synthetic_{dev,holdout}.jsonl` and
`synthetic_manifest.json` into the KB's eval directory. Run records go to the git-ignored
`data/reports/synthetic/<run_id>/`.
"""

