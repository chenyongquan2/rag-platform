# ---- seams (replaced in unit tests) ------------------------------------------------------------


def load_pages(cfg: KnowledgeBaseConfig, settings: ServiceSettings) -> list[Page]:
    return load_clean_pages(cfg, settings)


def _profile_settings(
    settings: ServiceSettings, config: GeneratorConfig | CriticConfig
) -> ServiceSettings:
    profile = getattr(settings, f"chat_{config.profile}").model_copy(
        update={
            "model": config.model,
            "max_tokens": config.max_tokens,
            "temperature": config.temperature,
        }
    )
    return settings.model_copy(update={f"chat_{config.profile}": profile})


def build_generator_model(settings: ServiceSettings, config: GeneratorConfig) -> BaseChatModel:
    from rag.llm import make_chat_model

    return make_chat_model(config.profile, _profile_settings(settings, config))


def build_critic_model(settings: ServiceSettings, config: CriticConfig) -> BaseChatModel:
    from rag.llm import make_chat_model

    return make_chat_model(config.profile, _profile_settings(settings, config))


# ---- files -------------------------------------------------------------------------------------


def _write_jsonl(path: Path, rows: Sequence[BaseModel]) -> None:
    text = "".join(r.model_dump_json() + "\n" for r in rows)
    path.write_text(text, encoding="utf-8", newline="\n")


def _read_jsonl[T: BaseModel](path: Path, cls: type[T]) -> list[T]:
    if not path.is_file():
        return []
    lines = path.read_text(encoding="utf-8").splitlines()
    return [cls.model_validate_json(line) for line in lines if line.strip()]


def _write_json(path: Path, data: Any) -> None:
    text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")


def _run_dir(args: argparse.Namespace) -> Path:
    run = Path(args.run)
    if not (run / SPANS).is_file():
        raise UsageError(f"{run}: no {SPANS}; run `sample` first")
    return run


def _spent(settings: ServiceSettings) -> float:
    return CostLedger.from_settings(settings).total_spent()


def _usage(records: Sequence[GenerationRecord | CritiqueRecord]) -> Usage:
    total = Usage()
    for r in records:
        total = total + r.usage
    return total


def _usage_line(name: str, usage: Usage) -> str:
    return (
        f"{name}: {usage.calls} calls, prompt {usage.prompt_tokens}, completion "
        f"{usage.completion_tokens} (reasoning {usage.reasoning_tokens}), {usage.cny:.4f} CNY"
    )


