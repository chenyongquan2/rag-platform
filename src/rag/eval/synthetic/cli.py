def _public_pages(cfg: KnowledgeBaseConfig) -> list[str]:
    qs = load_question_set(_question_file(cfg, None), kb=cfg.kb)
    return sorted({p for q in qs.questions for p in q.relevant_pages})


def _sample(args: argparse.Namespace, settings: ServiceSettings) -> int:
    """A new run, or with `--extend RUN` more spans appended to that run (never from a page the
    run already has), so a pilot's records stay valid when the run needs more questions."""
    cfg, _public = _kb_config(settings, args.kb)
    public = [] if args.no_exclude_public else _public_pages(cfg)
    previous: list[Span] = []
    batches: list[dict[str, Any]] = []
    if args.extend:
        run = _run_dir(argparse.Namespace(run=args.extend))
        previous = _read_jsonl(run / SPANS, Span)
        batches = json.loads((run / SAMPLE).read_text(encoding="utf-8"))["batches"]
    exclude = sorted({*public, *(s.doc_id for s in previous)})
    config = SamplerConfig(
        n=args.n,
        seed=args.seed,
        span_chars=args.span_chars,
        min_chars=args.min_chars,
        exclude_pages=exclude,
    )
    pages = load_pages(cfg, settings)
    result = sample_spans(pages, config)
    if not args.extend:
        label = f"synthetic-{args.label}" if args.label else "synthetic"
        out = Path(args.out_dir) if args.out_dir else repo_path(REPORTS_ROOT)
        run = out / make_run_id(cfg.kb, label)
        run.mkdir(parents=True)
    _write_jsonl(run / SPANS, [*previous, *result.spans])
    summary = result.summary()
    summary["config"]["exclude_pages"] = (
        f"{len(public)} public question pages, {len(previous)} pages already in the run"
    )
    _write_json(run / SAMPLE, {"kb": cfg.kb, "batches": [*batches, summary]})
    print(f"wrote {run}")
    print(
        f"spans {len(result.spans)} of {config.n} (run total {len(previous) + len(result.spans)}); "
        f"pages {result.pages_total}, excluded {result.pages_excluded}, skipped "
        f"{result.pages_skipped}, shortfall {result.shortfall}"
    )
    return 0


def _batches[T](items: Sequence[T], size: int) -> list[Sequence[T]]:
    return [items[i : i + size] for i in range(0, len(items), size)]


def _generate(args: argparse.Namespace, settings: ServiceSettings) -> int:
    run = _run_dir(args)
    spans = _read_jsonl(run / SPANS, Span)
    config = GeneratorConfig(
        concurrency=args.concurrency, **({"model": args.model} if args.model else {})
    )
    check_models_differ(config, CriticConfig())
    kept = [
        g
        for g in _read_jsonl(run / GENERATIONS, GenerationRecord)
        if g.error not in TRANSIENT_ERRORS
    ]
    done = {g.span_id for g in kept}
    todo = [s for s in spans if s.span_id not in done]
    if args.limit is not None:
        todo = todo[: args.limit]
    print(f"ledger: spent {_spent(settings):.4f} CNY; {len(todo)} spans to generate")
    if not todo:
        return 0
    model = build_generator_model(settings, config)
    order = {s.span_id: i for i, s in enumerate(spans)}
    new: list[GenerationRecord] = []

    async def work() -> None:  # one event loop for every batch: the model's clients belong to it
        for batch in _batches(todo, args.batch):
            new.extend(await generate_questions(batch, model, config=config))
            rows = sorted([*kept, *new], key=lambda g: order[g.span_id])
            _write_jsonl(run / GENERATIONS, rows)

    try:
        asyncio.run(work())
    finally:
        failed = Counter(g.error for g in new if g.error)
        print(
            f"generated {sum(g.question is not None for g in new)} of {len(new)}; "
            f"errors {dict(failed)}"
        )
        print(_usage_line("usage", _usage(new)))
    return 0


def _critique(args: argparse.Namespace, settings: ServiceSettings) -> int:
    run = _run_dir(args)
    spans = _read_jsonl(run / SPANS, Span)
    gens = [g for g in _read_jsonl(run / GENERATIONS, GenerationRecord) if g.question]
    config = CriticConfig(concurrency=args.concurrency)
    check_models_differ(GeneratorConfig(), config)
    kept = [
        c for c in _read_jsonl(run / CRITIQUES, CritiqueRecord) if c.error not in TRANSIENT_ERRORS
    ]
    done = {(c.span_id, c.criterion) for c in kept}
    todo = [(g.span_id, c) for g in gens for c in CRITERIA if (g.span_id, c) not in done]
    print(f"ledger: spent {_spent(settings):.4f} CNY; {len(todo)} critiques to run")
    if not todo:
        return 0
    model = build_critic_model(settings, config)
    order = {s.span_id: i for i, s in enumerate(spans)}
    new: list[CritiqueRecord] = []

    async def work() -> None:  # one event loop for every batch: the model's clients belong to it
        for batch in _batches(todo, args.batch):
            new.extend(await critique_questions(spans, gens, model, config=config, criteria=batch))
            rows = sorted(
                [*kept, *new], key=lambda c: (order[c.span_id], CRITERIA.index(c.criterion))
            )
            _write_jsonl(run / CRITIQUES, rows)

    try:
        asyncio.run(work())
    finally:
        failed = Counter(c.error for c in new if c.error)
        print(f"critiques {len(new)}; errors {dict(failed)}")
        print(_usage_line("usage", _usage(new)))
    return 0


def _project(args: argparse.Namespace, settings: ServiceSettings) -> int:
    run = _run_dir(args)
    gens = _read_jsonl(run / GENERATIONS, GenerationRecord)
    crits = _read_jsonl(run / CRITIQUES, CritiqueRecord)
    if not gens:
        raise UsageError(f"{run}: no generations yet")
    g_usage, c_usage = _usage(gens), _usage(crits)
    per_gen = g_usage.cny / len(gens)
    questions = {c.span_id for c in crits}
    per_question = c_usage.cny / len(questions) if questions else 0.0
    parsed = sum(g.question is not None for g in gens) / len(gens)
    projected = args.n * (per_gen + parsed * per_question)
    remaining = max(0.0, projected - g_usage.cny - c_usage.cny)
    spent = _spent(settings)
    lines = [
        _usage_line(f"generation ({len(gens)} spans)", g_usage),
        _usage_line(f"critique ({len(questions)} questions)", c_usage),
        f"per span: generation {per_gen:.5f} CNY; critique {per_question:.5f} CNY per question; "
        f"{parsed:.0%} of spans gave a question",
        f"projected for {args.n} spans: {projected:.3f} CNY ({remaining:.3f} still to spend)",
        f"ledger: spent {spent:.4f} CNY -> projected {spent + remaining:.4f} CNY "
        f"(stop at {settings.budget_stop_cny:.2f})",
    ]
    print("\n".join(lines))
    return 0


def _corpus_source(cfg: KnowledgeBaseConfig) -> dict[str, Any]:
    manifest = (cfg.source.model_extra or {}).get("manifest")
    if not manifest:
        return {}
    try:
        data = json.loads(repo_path(manifest).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"manifest": manifest}
    corpus = data.get("corpus", {})
    return {
        "manifest": manifest,
        "repo_id": corpus.get("repo_id"),
        "revision": corpus.get("revision"),
        "license": corpus.get("license"),
    }


def _overlap_stats(values: Sequence[float]) -> dict[str, float | None]:
    if not values:
        return {"median": None, "p90": None, "mean": None}
    ordered = sorted(values)
    return {
        "median": median(ordered),
        "p90": ordered[min(len(ordered) - 1, int(0.9 * len(ordered)))],
        "mean": round(sum(ordered) / len(ordered), 4),
    }


def _build(args: argparse.Namespace, settings: ServiceSettings) -> int:
    run = _run_dir(args)
    cfg, _public = _kb_config(settings, args.kb)
    spans = {s.span_id: s for s in _read_jsonl(run / SPANS, Span)}
    gens = _read_jsonl(run / GENERATIONS, GenerationRecord)
    crits = _read_jsonl(run / CRITIQUES, CritiqueRecord)
    batches = json.loads((run / SAMPLE).read_text(encoding="utf-8"))["batches"]
    filters = FilterConfig(max_copy_run=args.max_copy_run)
    scores: dict[str, dict[str, float | None]] = {}
    rationales: dict[str, dict[str, str]] = {}
    for c in crits:
        scores.setdefault(c.span_id, {})[c.criterion] = c.score
        rationales.setdefault(c.span_id, {})[c.criterion] = c.rationale
    generator = GeneratorConfig(**({"model": gens[0].model} if gens else {}))
    critic = CriticConfig(**({"model": crits[0].model} if crits else {}))

    reasons_count: Counter[str] = Counter()
    only_reason: Counter[str] = Counter()
    kept: list[LabeledQuestion] = []
    rejected: list[dict[str, Any]] = []
    seen: set[str] = set()
    runs_all: list[float] = []
    runs_kept: list[float] = []
    recall_kept: list[float] = []
    redacted = 0
    for gen in gens:
        span = spans[gen.span_id]
        q_scores = scores.get(gen.span_id, {})
        reasons = rejection_reasons(
            question=gen.question,
            answer=gen.answer,
            span=span.text,
            scores=q_scores,
            config=filters,
        )
        overlap = lexical_overlap(gen.question or "", span.text)
        if gen.question:
            runs_all.append(overlap.longest_run)
            key = " ".join(gen.question.lower().split())
            if key in seen:
                reasons.append("duplicate_question")
            seen.add(key)
        reasons_count.update(reasons)
        if len(reasons) == 1:
            only_reason[reasons[0]] += 1
        if reasons:
            rejected.append(
                {
                    "span_id": gen.span_id,
                    "question": gen.question,
                    "reasons": reasons,
                    "scores": q_scores,
                }
            )
            continue
        span_text, n_redacted = redact_secrets(span.text)
        question, n_q = redact_secrets(gen.question or "")
        answer, n_a = redact_secrets(gen.answer or "")
        redacted += n_redacted + n_q + n_a
        runs_kept.append(overlap.longest_run)
        recall_kept.append(overlap.content_recall)
        kept.append(
            LabeledQuestion(
                qid=f"{QID_PREFIX}:{gen.span_id}",
                question=question,
                answer=answer,
                relevant_pages=[gen.doc_id],
                meta={
                    "span": span_text,
                    "span_start": span.start,
                    "span_end": span.end,
                    "source_rel": span.source_rel,
                    "doc_type": span.doc_type,
                    "stratum": span.stratum,
                    "scores": q_scores,
                    "rationales": rationales.get(gen.span_id, {}),
                    "overlap": overlap.model_dump(),
                },
            )
        )
    by_qid = {q.qid: q for q in kept}
    dev_ids, holdout_ids = split_dev_holdout(
        [(q.qid, str(q.meta["stratum"])) for q in kept],
        seed=args.seed,
        holdout_share=args.holdout_share,
        min_each=args.min_each,
    )
    out = (
        Path(args.out_dir)
        if args.out_dir
        else repo_path(cfg.eval.dir or f"evals/datasets/{cfg.kb}")
    )
    files: dict[str, dict[str, Any]] = {}
    for name, ids in ((DEV_FILE, dev_ids), (HOLDOUT_FILE, holdout_ids)):
        sha = save_question_set([by_qid[i] for i in ids], out / name)
        files[name] = {"sha256": sha, "questions": len(ids)}
    split_strata = {
        name: dict(Counter(str(by_qid[i].meta["stratum"]) for i in ids))
        for name, ids in (("dev", dev_ids), ("holdout", holdout_ids))
    }
    g_usage, c_usage = _usage(gens), _usage(crits)
    counts = {
        "spans": len(spans),
        "generation_calls": len(gens),
        "generated": sum(g.question is not None for g in gens),
        "kept": len(kept),
        "dev": len(dev_ids),
        "holdout": len(holdout_ids),
    }
    provenance = collect_provenance(settings=settings, models={})
    manifest = {
        "created_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "kb": cfg.kb,
        "run": display_path(run),
        "spec": "P1-05",
        "git_commit": provenance.git_commit,
        "source": _corpus_source(cfg),
        "sampler": [b["config"] for b in batches],
        "generator": generator.model_dump(),
        "critic": critic.model_dump(),
        "prompt_versions": {
            "generation": gens[0].prompt_version if gens else GENERATION_PROMPT_VERSION,
            "critique": crits[0].prompt_version if crits else CRITIQUE_PROMPT_VERSION,
        },
        "seeds": {"sample": [b["config"]["seed"] for b in batches], "split": args.seed},
        "thresholds": filters.model_dump(),
        "split": {"holdout_share": args.holdout_share, "min_each": args.min_each},
        "counts": counts,
        "rejections": dict(sorted(reasons_count.items())),
        "rejections_only_reason": dict(sorted(only_reason.items())),
        "redacted_tokens": redacted,
        "strata": split_strata,
        "usage": {"generation": g_usage.model_dump(), "critique": c_usage.model_dump()},
        "files": files,
        "license": LICENCE,
    }
    _write_json(out / MANIFEST_FILE, manifest)
    report = {
        "counts": counts,
        "rejections": manifest["rejections"],
        "rejections_only_reason": manifest["rejections_only_reason"],
        "rejected_questions": len(rejected),
        "longest_run_all": _overlap_stats(runs_all),
        "longest_run_kept": _overlap_stats(runs_kept),
        "content_recall_kept": _overlap_stats(recall_kept),
        "score_distribution": {
            c: dict(Counter(str(s.get(c)) for s in scores.values())) for c in CRITERIA
        },
        "strata": split_strata,
        "rejected": rejected,
    }
    _write_json(run / "filter_report.json", report)
    print(f"wrote {out / DEV_FILE}, {out / HOLDOUT_FILE}, {out / MANIFEST_FILE}")
    print(json.dumps({"counts": counts, "rejections": manifest["rejections"]}, indent=1))
    return 0


# ---- entry point -------------------------------------------------------------------------------


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m rag.eval.synthetic",
        description="Synthetic questions: sample spans, generate, critique, split (spec P1-05).",
    )
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("sample", help="random spans of the cleaned pages (no model)")
    p.add_argument("--kb", required=True)
    p.add_argument("--n", type=int, default=420)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--span-chars", type=int, default=2000)
    p.add_argument("--min-chars", type=int, default=400)
    p.add_argument(
        "--no-exclude-public",
        action="store_true",
        help="also sample the public questions' source pages",
    )
    p.add_argument("--label")
    p.add_argument("--out-dir", help=f"default: {REPORTS_ROOT}")
    p.add_argument("--extend", metavar="RUN", help="append the new spans to this run")
    p = sub.add_parser("generate", help="one question per span (costs money)")
    p.add_argument("--run", required=True)
    p.add_argument("--limit", type=int)
    p.add_argument("--concurrency", type=int, default=4)
    p.add_argument("--batch", type=int, default=20)
    p.add_argument("--model", help="generator model (default: deepseek-v4-flash)")
    p = sub.add_parser("critique", help="three 1-5 critiques per question (costs money)")
    p.add_argument("--run", required=True)
    p.add_argument("--concurrency", type=int, default=4)
    p.add_argument("--batch", type=int, default=60)
    p = sub.add_parser("project", help="cost of n spans from the run's ledger lines")
    p.add_argument("--run", required=True)
    p.add_argument("--n", type=int, default=420)
    p = sub.add_parser("build", help="filter, split, write the dev and holdout sets")
    p.add_argument("--run", required=True)
    p.add_argument("--kb", required=True)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--holdout-share", type=float, default=0.5)
    p.add_argument("--min-each", type=int, default=100)
    p.add_argument("--max-copy-run", type=int, default=FilterConfig().max_copy_run)
    p.add_argument("--out-dir", help="default: the KB's eval directory")
    return parser


_COMMANDS = {
    "sample": _sample,
    "generate": _generate,
    "critique": _critique,
    "project": _project,
    "build": _build,
}


def main(argv: Sequence[str] | None = None, *, settings: ServiceSettings | None = None) -> int:
    args = _parser().parse_args(argv)
    settings = settings if settings is not None else ServiceSettings()
    for name in ("limit", "n", "concurrency", "batch"):
        value = getattr(args, name, None)
        if value is not None and value < 1:
            print(f"error: --{name} must be a positive integer", file=sys.stderr)
            return 2
    try:
        return _COMMANDS[args.command](args, settings)
    except UsageError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except (BudgetExceeded, ValueError) as exc:
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
