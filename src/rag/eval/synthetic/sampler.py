"""Random spans of the raw cleaned page text for question generation (spec P1-05, design s14-2).

Spans are cut from each page's text after the knowledge base's read and clean rules, never from
the index chunks: a question generated from a chunk has its answer inside one chunk of today's
chunking, so a chunk-size ablation would favour the current size.

Sampling is stratified: a stratum is the source repository plus the document type
(`huggingface/transformers:markdown`), the n spans are allocated to strata in proportion to their
page counts (largest remainder), and pages are drawn without replacement, one span per page. A
span starts at a random line start and is `span_chars` long, extended to the end of its last line
(at most `max_line_extension` more characters). Tiny, code-only and boilerplate spans are
rejected; a page gets `attempts` tries before it is skipped and the next page of its stratum is
drawn. The final list is shuffled with the same seed, so the first spans (a pilot) cover the
strata in proportion too.
"""

from __future__ import annotations

import hashlib
import random
import re
from collections import Counter
from collections.abc import Iterable, Mapping, Sequence
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class Page(BaseModel):
    """One cleaned page (a kept Document of the knowledge base's read + clean stages)."""

    model_config = ConfigDict(frozen=True)

    doc_id: str
    source_rel: str
    doc_type: str
    language: str
    text: str


class Span(BaseModel):
    model_config = ConfigDict(frozen=True)

    span_id: str
    doc_id: str
    source_rel: str
    doc_type: str
    stratum: str
    start: int
    """Character offsets into the page's cleaned text."""
    end: int
    text: str


class SamplerConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    n: int = Field(default=420, ge=1)
    seed: int = 0
    span_chars: int = Field(default=2000, ge=1)
    """HF rag_evaluation cuts 2,000-character contexts."""
    max_line_extension: int = Field(default=300, ge=0)
    min_chars: int = Field(default=400, ge=1)
    min_prose_share: float = Field(default=0.3, ge=0, le=1)
    """Share of the span's characters in prose lines (outside code fences, not table rows)."""
    attempts: int = Field(default=3, ge=1)
    languages: list[str] = Field(default_factory=lambda: ["en"])
    exclude_pages: list[str] = Field(default_factory=list)
    """doc_ids never sampled (the public questions' source pages, see docs/decisions.md)."""


class SampleResult(BaseModel):
    config: SamplerConfig
    spans: list[Span]
    pages_total: int
    pages_excluded: dict[str, int]
    """Pages left out before sampling: `excluded` (listed), `language`."""
    strata_pages: dict[str, int]
    allocation: dict[str, int]
    pages_skipped: dict[str, int]
    """Pages drawn but skipped because every attempt gave a bad span, by the last reason."""
    span_problems: dict[str, int]
    """Every rejected attempt, by reason."""
    shortfall: dict[str, int]
    """Strata that ran out of usable pages: spans missing."""

    def summary(self) -> dict[str, Any]:
        return self.model_dump(exclude={"spans"})


def stratum_of(page: Page) -> str:
    """`<owner>/<repo>:<doc_type>`; the first two path parts are the source repository."""
    repo = "/".join(page.source_rel.split("/")[:2])
    return f"{repo}:{page.doc_type}"


def allocate(sizes: Mapping[str, int], n: int) -> dict[str, int]:
    """Split n over strata in proportion to `sizes` (largest remainder, ties by name); no
    stratum gets more than its size."""
    total = sum(sizes.values())
    if n > total:
        raise ValueError(f"cannot draw {n} from {total} pages")
    if n == 0 or total == 0:
        return dict.fromkeys(sizes, 0)
    quotas = {k: n * v / total for k, v in sizes.items()}
    out = {k: min(int(q), sizes[k]) for k, q in quotas.items()}
    order = sorted(sizes, key=lambda k: (-(quotas[k] - int(quotas[k])), k))
    while sum(out.values()) < n:
        for key in order:
            if sum(out.values()) >= n:
                break
            if out[key] < sizes[key]:
                out[key] += 1
    return out


_FENCE = re.compile(r"^\s*(```|~~~)")
_WORD = re.compile(r"[A-Za-z][A-Za-z'-]*")
_BOILERPLATE = (
    re.compile(r"licensed under the apache license", re.I),
    re.compile(r"permissions and limitations under the license", re.I),
    re.compile(r"this file is (?:automatically )?(?:auto-?)?generated", re.I),
    re.compile(r"do not edit this file", re.I),
)


def _is_prose(line: str) -> bool:
    stripped = line.strip()
    if not stripped or stripped.startswith("|"):
        return False
    tokens = stripped.split()
    if len(tokens) < 6:
        return False
    words = sum(bool(_WORD.fullmatch(t.strip(".,;:!?()\"'*`"))) for t in tokens)
    return words / len(tokens) >= 0.6


def prose_share(text: str) -> float:
    """Characters in prose lines over all non-blank characters; lines inside code fences and
    table rows are not prose. A span may start inside a fence; that part counts as prose."""
    total = prose = 0
    in_fence = False
    for line in text.splitlines():
        if _FENCE.match(line):
            in_fence = not in_fence
            total += len(line.strip())
            continue
        size = len(line.strip())
        total += size
        if not in_fence and _is_prose(line):
            prose += size
    return prose / total if total else 0.0


def span_problem(text: str, config: SamplerConfig) -> str | None:
    """`tiny`, `boilerplate`, `code_only` or None for a usable span."""
    if len(text.strip()) < config.min_chars:
        return "tiny"
    if any(p.search(text) for p in _BOILERPLATE):
        return "boilerplate"
    if prose_share(text) < config.min_prose_share:
        return "code_only"
    return None


def _cut(text: str, rng: random.Random, config: SamplerConfig) -> tuple[int, int]:
    if len(text) <= config.span_chars:
        return 0, len(text)
    start = rng.randrange(0, len(text) - config.span_chars + 1)
    start = text.rfind("\n", 0, start) + 1  # back to the start of the line
    end = start + config.span_chars
    newline = text.find("\n", end - 1)
    if newline == -1:
        newline = len(text)
    if newline - end <= config.max_line_extension:
        end = newline
    return start, end


def span_id(doc_id: str, start: int) -> str:
    return hashlib.sha1(f"{doc_id}@{start}".encode()).hexdigest()[:12]


def _draw(
    page: Page, stratum: str, rng: random.Random, config: SamplerConfig
) -> tuple[Span | None, list[str]]:
    """A usable span of `page` within `config.attempts` tries, and the reasons of failed ones."""
    reasons: list[str] = []
    for _ in range(config.attempts):
        start, end = _cut(page.text, rng, config)
        piece = page.text[start:end]
        reason = span_problem(piece, config)
        if reason is None:
            span = Span(
                span_id=span_id(page.doc_id, start),
                doc_id=page.doc_id,
                source_rel=page.source_rel,
                doc_type=page.doc_type,
                stratum=stratum,
                start=start,
                end=end,
                text=piece,
            )
            return span, reasons
        reasons.append(reason)
        if len(page.text) <= config.span_chars:
            break  # the span was the whole page; another try gives the same text
    return None, reasons


def sample_spans(pages: Iterable[Page], config: SamplerConfig) -> SampleResult:
    pages = list(pages)
    excluded = set(config.exclude_pages)
    removed: Counter[str] = Counter()
    by_stratum: dict[str, list[Page]] = {}
    for page in pages:
        if page.doc_id in excluded:
            removed["excluded"] += 1
        elif page.language not in config.languages:
            removed["language"] += 1
        else:
            by_stratum.setdefault(stratum_of(page), []).append(page)
    sizes = {k: len(v) for k, v in sorted(by_stratum.items())}
    allocation = allocate(sizes, config.n)

    rng = random.Random(config.seed)
    spans: list[Span] = []
    skipped: Counter[str] = Counter()
    problems: Counter[str] = Counter()
    shortfall: dict[str, int] = {}
    for stratum in sorted(by_stratum):
        candidates = sorted(by_stratum[stratum], key=lambda p: p.doc_id)
        rng.shuffle(candidates)
        want = allocation[stratum]
        got = 0
        for page in candidates:
            if got >= want:
                break
            span, reasons = _draw(page, stratum, rng, config)
            problems.update(reasons)
            if span is None:
                skipped[reasons[-1]] += 1
            else:
                spans.append(span)
                got += 1
        if got < want:
            shortfall[stratum] = want - got
    rng.shuffle(spans)
    return SampleResult(
        config=config,
        spans=spans,
        pages_total=len(pages),
        pages_excluded=dict(removed),
        strata_pages=sizes,
        allocation=allocation,
        pages_skipped=dict(skipped),
        span_problems=dict(problems),
        shortfall=shortfall,
    )


def pages_from_documents(documents: Sequence[Any]) -> list[Page]:
    """Cleaned LlamaIndex Documents (`KbProcessor.clean` output) -> pages."""
    from llama_index.core.schema import MetadataMode

    return [
        Page(
            doc_id=d.metadata["doc_id"],
            source_rel=d.metadata["source_rel"],
            doc_type=d.metadata["doc_type"],
            language=str(d.metadata.get("language") or "und"),
            text=d.get_content(MetadataMode.NONE),
        )
        for d in documents
    ]


def load_clean_pages(cfg: Any, settings: Any) -> list[Page]:
    """Every page of the knowledge base after its read and clean rules (no limit, no chunking)."""
    from rag.ingest.build import KbProcessor
    from rag.registry import connectors

    extra = dict(cfg.source.model_extra or {})
    extra["limit"] = None
    connector = connectors.create(cfg.source.connector, kb=cfg.kb, settings=settings, **extra)
    proc = KbProcessor(cfg, settings=settings)
    read = proc.read(connector.documents())
    return pages_from_documents(proc.clean(read.documents))
